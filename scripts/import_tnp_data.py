"""
Import The New Project's unit sheet into `tnp/data/humans.json` and
`tnp/data/technology.json`.

    python3 scripts/import_tnp_data.py <workbook> [--data-version 2]

The workbook is `The New Project unit sheet v3.xlsx` in the Drive folder
**The New Project** (`Units/`, Drive id 1NhVe5RxaHVzrfSv6GXtKk8wS1eS14JqG):
the `.xlsx` itself, or the JSON the Google Drive connector's
`download_file_content` saves (`{"content": <base64>, ...}`), as
`scripts/import_from_workbook.py` reads one. Two of its tabs are read,
each whole, by their headers:

- **Humans** (Building, Type, Name, Materials, Gems, inf, arm, air,
  Initiative, Ability, picture, Count, trait1, trait2, scouting, trait3)
  into `humans.json`: every unit, keyed by slug, and the four
  infrastructure upgrades and the base upgrade, Command and Control
  CPU -- the rows with a name and no Building. The
  sheet's "Gems" column is **gold** (docs/tnp-rules.md, 2.2), and its
  Count is the unit's supply. A unit's traits are its icons (trait1 to
  trait3), the board's own record of them; its Ability text is kept
  whole beside them.
- **Technology** (Count, Title, Type, Materials, ability, iconn, colorr,
  Short Ability) into `technology.json`: every card row, keyed by slug,
  its deck from `colorr` (minerals1 the blue minerals, minerals2 the
  orange, gems the gems).

What is refused rather than guessed: a rating other than Strong, Fair,
Weak or Poor -- the sheet writes Poor as Can't, and Can't, Poor and X
all read as Poor (docs/tnp-rules.md, 4.3) -- a unit type, Building,
trait icon, tech type or deck the tables below do not know, and two rows
with one slug. What is reported and left out: a tech row with no Count
(Positioning, Air Cover and Shields in v3), and a row with no name (the
Humans tab's total of the Count column). Columns with no header are not
read.

Names are kept as the sheet spells them, and slugs are made from them:
lower case, every run of other characters one underscore. Both files say
at their head that they are regenerated and never edited by hand: a
wrong value is corrected in the sheet and imported again.

Each file keeps the `data_version` it has unless `--data-version` gives
it a new one. Needs `openpyxl` (`pip install openpyxl`), which the bot
does not. See docs/design/tnp.md, "The data".
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import re
import sys
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "tnp" / "data"
HUMANS_JSON = DATA / "humans.json"
TECHNOLOGY_JSON = DATA / "technology.json"

SOURCE = {
    "file": "The New Project unit sheet v3.xlsx",
    "drive_id": "1NhVe5RxaHVzrfSv6GXtKk8wS1eS14JqG",
}

HEADER_NOTE = (
    "REGENERATED by scripts/import_tnp_data.py from the unit sheet named "
    "in `source`; never edit it by hand. Correct the sheet and import again."
)

#: The sheet's spellings of a rating, lower-cased.
RATINGS = {
    "strong": "strong",
    "fair": "fair",
    "weak": "weak",
    "poor": "poor",
    "can't": "poor",
    "can’t": "poor",
    "x": "poor",
}

UNIT_TYPES = {"inf": "infantry", "arm": "armored", "air": "air"}

#: The Building column, lower-cased and stripped: the facility that
#: builds the unit, and the unit upgrade it needs (None for none).
#: The upgrades' slugs are human_board.json's.
BUILDINGS = {
    "barracks": ("barracks", None),
    "barracks stealth upgrade": ("barracks", "stealth_upgrade"),
    "barracks cyborg upgrade": ("barracks", "cyborg_upgrade"),
    "factory": ("factory", None),
    "factory upgrade - robotic facility": ("factory", "robotic_facility"),
    "airport": ("airport", None),
    "airport upgrade": ("airport", "fighter_bomber_upgrade"),
    "base defense": ("base_defenses", None),
    "advanced base defense": ("base_defenses", "laser_cannon_upgrade"),
}

#: The infrastructure upgrade rows (a name and no Building), by the
#: lower-cased name: the facility each upgrades.
INFRASTRUCTURE = {
    "barracks upgrade": "barracks",
    "factory upgrade": "factory",
    "airport upgrade": "airport",
    "base defense upgrade": "base_defenses",
}

#: The base upgrades (a name and no Building): bought like an
#: infrastructure upgrade, but of the base, not of a facility -- saved
#: with no facility. Command and Control CPU opens attack spot C (the
#: author, 2026-11-06, moving it out of the tech deck).
BASE_UPGRADES = {"command and control cpu"}

#: A trait icon's file name, lower-cased, to the trait. "-" and an empty
#: cell are no trait.
TRAIT_ICONS = {
    "repair.png": "repair",
    "harvest.png": "harvest",
    "scouting.png": "scouting",
    "mechanical.png": "mechanical",
    "tough.png": "tough",
    "splash.png": "splash",
    "transformericon.png": "transformation",
    "transport.png": "transport",
    "base.png": "base_defense",
}
NO_TRAIT = {"", "-"}

TECH_TYPES = {
    "tech facility": "tech_facility",
    "building tech": "building_tech",
    "tactic card": "tactic",
}

DECKS = {
    "minerals1": "blue_minerals",
    "minerals2": "orange_minerals",
    "gems": "gems",
}


class SheetError(ValueError):
    """A cell the importer will not guess at."""


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.strip().lower()).strip("_")


def text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value).strip()


def number(value, where: str, *, blank: int | None = 0) -> int | None:
    cell = text(value)
    if not cell:
        return blank
    try:
        return int(float(cell))
    except ValueError:
        raise SheetError(f"{where}: {cell!r} is not a number") from None


def rating(value, where: str) -> str:
    cell = text(value).lower()
    if cell not in RATINGS:
        raise SheetError(
            f"{where}: rating {text(value)!r} is not Strong, Fair, Weak or Poor "
            "(Can't, Poor and X all read as Poor)"
        )
    return RATINGS[cell]


def workbook_bytes(path: Path) -> bytes:
    """The `.xlsx` itself, or the one inside a connector's JSON dump."""
    raw = path.read_bytes()
    if raw[:2] == b"PK":
        return raw
    return base64.b64decode(json.loads(raw)["content"])


def tab_rows(workbook, title: str) -> list[dict[str, object]]:
    """A tab's rows as dicts by header, headed columns only, blank rows
    dropped."""
    sheets = {name.strip(): name for name in workbook.sheetnames}
    if title not in sheets:
        raise SheetError(
            f"The workbook has no tab {title!r}: it has "
            + ", ".join(repr(name) for name in workbook.sheetnames)
        )
    rows = workbook[sheets[title]].iter_rows(values_only=True)
    header = [text(cell) for cell in next(rows)]
    out = []
    for row in rows:
        record = {
            name: row[index] if index < len(row) else None
            for index, name in enumerate(header)
            if name
        }
        if any(text(value) for value in record.values()):
            out.append(record)
    return out


def import_humans(rows: list[dict[str, object]], report: list[str]) -> dict:
    units: dict[str, dict] = {}
    upgrades: dict[str, dict] = {}
    for line, row in enumerate(rows, start=2):
        name = text(row.get("Name"))
        if not name:
            report.append(f"Humans row {line}: no name, left out ({_summary(row)})")
            continue
        where = f"Humans row {line} ({name})"
        building = text(row.get("Building")).lower()
        slug = slugify(name)
        cost = {
            "materials": number(row.get("Materials"), where),
            "gold": number(row.get("Gems"), where),
        }
        if not building:
            facility = INFRASTRUCTURE.get(name.lower())
            if facility is None and name.lower() not in BASE_UPGRADES:
                raise SheetError(f"{where}: a row with no Building is not a known infrastructure or base upgrade")
            if slug in upgrades:
                raise SheetError(f"{where}: a second upgrade with the slug {slug!r}")
            upgrades[slug] = {
                "name": name,
                "facility": facility,
                "cost": cost,
                "ability": text(row.get("Ability")),
            }
            continue
        if building not in BUILDINGS:
            raise SheetError(f"{where}: Building {text(row.get('Building'))!r} is not known")
        facility, upgrade = BUILDINGS[building]
        unit_type = text(row.get("Type")).lower()
        if unit_type not in UNIT_TYPES:
            raise SheetError(f"{where}: Type {text(row.get('Type'))!r} is not Inf, Arm or Air")
        traits = []
        for column in ("trait1", "trait2", "trait3"):
            icon = text(row.get(column)).lower()
            if icon in NO_TRAIT:
                continue
            if icon not in TRAIT_ICONS:
                raise SheetError(f"{where}: trait icon {text(row.get(column))!r} is not known")
            traits.append(TRAIT_ICONS[icon])
        scouting = number(row.get("scouting"), where)
        if scouting and "scouting" not in traits:
            raise SheetError(f"{where}: Scouting {scouting} with no scouting icon")
        if "scouting" in traits and not scouting:
            raise SheetError(f"{where}: a scouting icon with no scouting number")
        if slug in units:
            raise SheetError(f"{where}: a second unit with the slug {slug!r}")
        units[slug] = {
            "name": name,
            "type": UNIT_TYPES[unit_type],
            "building": text(row.get("Building")),
            "facility": facility,
            "upgrade": upgrade,
            "cost": cost,
            "attack": {
                "infantry": rating(row.get("inf"), where),
                "armored": rating(row.get("arm"), where),
                "air": rating(row.get("air"), where),
            },
            "initiative": number(row.get("Initiative"), where, blank=None),
            "traits": traits,
            "scouting": scouting,
            "ability": text(row.get("Ability")),
            "supply": number(row.get("Count"), where, blank=None),
            "picture": text(row.get("picture")),
        }
        if units[slug]["initiative"] is None or units[slug]["supply"] is None:
            raise SheetError(f"{where}: no Initiative or no Count")
    return {"units": units, "infrastructure_upgrades": upgrades}


def import_technology(rows: list[dict[str, object]], report: list[str]) -> dict:
    techs: dict[str, dict] = {}
    for line, row in enumerate(rows, start=2):
        name = text(row.get("Title"))
        if not name:
            report.append(f"Technology row {line}: no title, left out ({_summary(row)})")
            continue
        where = f"Technology row {line} ({name})"
        count = number(row.get("Count"), where, blank=None)
        if count is None:
            report.append(f"{where}: no Count, left out")
            continue
        kind = text(row.get("Type")).lower()
        if kind not in TECH_TYPES:
            raise SheetError(f"{where}: Type {text(row.get('Type'))!r} is not known")
        deck = text(row.get("colorr")).lower()
        if deck not in DECKS:
            raise SheetError(f"{where}: colorr {text(row.get('colorr'))!r} is not a known deck")
        slug = slugify(name)
        if slug in techs:
            raise SheetError(f"{where}: a second card with the slug {slug!r}")
        techs[slug] = {
            "name": name,
            "count": count,
            "type": TECH_TYPES[kind],
            "deck": DECKS[deck],
            "materials": number(row.get("Materials"), where, blank=None),
            "ability": text(row.get("ability")),
            "short_ability": text(row.get("Short Ability")),
            "icon": text(row.get("iconn")),
        }
    return {"techs": techs}


def _summary(row: dict[str, object]) -> str:
    return ", ".join(f"{key}={text(value)}" for key, value in row.items() if text(value))


def current_version(path: Path) -> int:
    try:
        return int(json.loads(path.read_text(encoding="utf-8"))["data_version"])
    except (OSError, ValueError, KeyError, TypeError):
        return 1


def write(path: Path, tab: str, body: dict, version: int | None) -> None:
    data = {
        "_comment": HEADER_NOTE,
        "data_version": version if version is not None else current_version(path),
        "source": {**SOURCE, "tab": tab},
        **body,
    }
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("workbook", type=Path)
    parser.add_argument(
        "--data-version", type=int,
        help="a new data_version for both files (default: keep each file's)",
    )
    options = parser.parse_args()

    from openpyxl import load_workbook

    workbook = load_workbook(io.BytesIO(workbook_bytes(options.workbook)), data_only=True)
    report: list[str] = []
    try:
        humans = import_humans(tab_rows(workbook, "Humans"), report)
        technology = import_technology(tab_rows(workbook, "Technology"), report)
    except SheetError as error:
        print(f"Refused: {error}", file=sys.stderr)
        return 1
    DATA.mkdir(parents=True, exist_ok=True)
    write(HUMANS_JSON, "Humans", {"faction": "humans", **humans}, options.data_version)
    write(TECHNOLOGY_JSON, "Technology", technology, options.data_version)
    for line in report:
        print(line)
    print(
        f"Wrote {len(humans['units'])} units and "
        f"{len(humans['infrastructure_upgrades'])} upgrades (infrastructure and base) to "
        f"{HUMANS_JSON.name}, {len(technology['techs'])} cards to {TECHNOLOGY_JSON.name}."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
